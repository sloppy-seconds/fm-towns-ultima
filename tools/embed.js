#!/usr/bin/env node
/*
 * tools/embed.js - turn a binary file into a C++ translation unit, so the port can carry it inside its own binary.
 *
 * WHY. One file the player has to keep beside the binary is one file too many, and the glyph ROM is the last of them:
 * the disc image and the saves are now optional after the first run, and everything else the port reads comes out of
 * the image. Embedding the ROM makes the whole distribution "a binary and your own disc".
 *
 * WHAT MAY BE EMBEDDED, and this is the line. The glyph ROM is generated from a public-domain BDF font, is not
 * Fujitsu code, and is already committed and shipped as assets/font-rom/FMT_FNT.ROM. The game's own fonts are disc
 * data, and putting those in the binary would be distributing the game, which the repository never does. So this tool
 * is for the one file, and the guard below refuses the extensions that would make it a way to smuggle media in.
 *
 * USAGE
 *   node tools/embed.js <input> <output.cpp> <symbol>
 *
 * Emits:
 *   const unsigned char <symbol>[];  const unsigned long <symbol>_size;
 *
 * The array is an initialiser list rather than a string literal because a string literal that long hits compiler
 * limits on some targets, and unsigned char avoids the sign and character-set questions entirely.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const [, , input, output, symbol] = process.argv;
if (!input || !output || !symbol) {
	console.error('usage: node tools/embed.js <input> <output.cpp> <symbol>');
	process.exit(2);
}
if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(symbol)) {
	console.error(`embed: "${symbol}" is not a C identifier`);
	process.exit(2);
}

// The same list the release guard uses for original media. A file with one of these extensions is not something this
// tool exists for, and a mistake here would put game data in a binary that is published.
const FORBIDDEN = /\.(exp|img|ccd|cue|sub|iso|hdm|d77|d88|hdf|fnt|snd|eup|mp3|dg3|tif|tiff|dat)$/i;
if (FORBIDDEN.test(input)) {
	console.error(`embed: refusing ${input}. ${path.extname(input)} is original media, not something to bake into a binary.`);
	process.exit(1);
}

const bytes = fs.readFileSync(input);
if (!bytes.length) {
	console.error(`embed: ${input} is empty`);
	process.exit(1);
}

const lines = [];
for (let i = 0; i < bytes.length; i += 20) {
	const chunk = [];
	for (let j = i; j < Math.min(i + 20, bytes.length); ++j) chunk.push('0x' + bytes[j].toString(16).padStart(2, '0'));
	lines.push('\t' + chunk.join(',') + ',');
}

const text = `// Generated by tools/embed.js from ${path.basename(input)}. Do not edit.
//
// ${bytes.length} bytes, embedded so the port does not need the file beside it. The source of the data, and the
// whole of what is established about its licence, is in assets/font-rom/README.md.

extern const unsigned char ${symbol}[];
extern const unsigned long ${symbol}_size;

const unsigned char ${symbol}[] = {
${lines.join('\n')}
};

const unsigned long ${symbol}_size = sizeof(${symbol});
`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, text);
console.log(`embed     ${input} -> ${output} (${bytes.length} bytes as ${symbol})`);
